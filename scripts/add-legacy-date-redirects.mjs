// Adds /YYYY/MM/DD/<slug>/ -> /<slug>/ redirects for every pre-2026 post that
// doesn't already have one.
//
// Why: the WordPress/Jekyll lineage served posts at date-prefixed permalinks.
// The original migration (scripts/classify-urls.mjs) only created redirects for
// URLs that happened to be in tsk-indexed-urls.csv, so Google keeps rediscovering
// date URLs for the other posts and logging them as 404s in Search Console.
// Posts dated 2026+ are skipped — they were authored in Astro and never had a
// date-prefixed URL.
//
// Run: node scripts/add-legacy-date-redirects.mjs && node scripts/generate-redirects.mjs
import fs from 'node:fs';
import path from 'node:path';

const BLOG_DIR = path.resolve('./src/content/blog');
const REDIRECTS_FILE = path.resolve('./src/data/redirects.ts');

const raw = fs.readFileSync(REDIRECTS_FILE, 'utf8');
const m = raw.match(/redirects:\s*RedirectEntry\[\]\s*=\s*(\[[\s\S]*?\]);/);
if (!m) { console.error('Could not parse redirects.ts'); process.exit(1); }
const existing = JSON.parse(m[1]);
const seen = new Set(existing.map((r) => r.from));

// One-off legacy URLs Google is still crawling that map to a live page.
const EXTRAS = [
  { from: '/randy-walker/', to: '/about/' },
  { from: '/posts/when-the-recruiter-becomes-the-bottleneck/', to: '/when-the-recruiter-becomes-the-bottleneck/' },
];

const added = [];
for (const e of EXTRAS) {
  if (seen.has(e.from)) continue;
  seen.add(e.from);
  added.push(e);
}

for (const name of fs.readdirSync(BLOG_DIR).sort()) {
  if (!name.endsWith('.md')) continue;
  const slug = name.slice(0, -3);
  const body = fs.readFileSync(path.join(BLOG_DIR, name), 'utf8');
  const d = body.match(/^date:\s*'?(\d{4})-(\d{2})-(\d{2})/m);
  if (!d) continue;
  const [, y, mo, dd] = d;
  if (Number(y) >= 2026) continue;
  const from = `/${y}/${mo}/${dd}/${slug}/`;
  if (seen.has(from)) continue;
  seen.add(from);
  added.push({ from, to: `/${slug}/` });
}

const all = [...existing, ...added].sort((a, b) => a.from.localeCompare(b.from));
const out = `// AUTO-GENERATED by scripts/classify-urls.mjs and
// scripts/add-legacy-date-redirects.mjs — do not edit by hand.
export interface RedirectEntry { from: string; to: string; }
export const redirects: RedirectEntry[] = ${JSON.stringify(all, null, 2)};
`;
fs.writeFileSync(REDIRECTS_FILE, out);
console.log(`Added ${added.length} redirects (${all.length} total).`);
